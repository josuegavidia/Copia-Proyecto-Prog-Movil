// Position-based realistic height default fallback
export const getPositionDefaultHeight = (position: Position): string => {
  switch (position) {
    case 'PG':
      return '1.88 m (6\'2")';
    case 'SG':
      return '1.96 m (6\'5")';
    case 'SF':
      return '2.01 m (6\'7")';
    case 'PF':
      return '2.08 m (6\'10")';
    case 'C':
      return '2.13 m (7\'0")';
    default:
      return '1.98 m (6\'6")';
  }
};

export const getPlayerBio = (
  name: string,
  position: Position,
  overrideHeight?: string,
  overrideCountry?: string,
  overrideFlag?: string
): PlayerBioInfo => {
  const found = PLAYER_BIO_DATA[name];
  if (found) {
    return {
      height: overrideHeight || found.height,
      country: overrideCountry || found.country,
      countryFlag: overrideFlag || found.countryFlag,
    };
  }

  return {
    height: overrideHeight || getPositionDefaultHeight(position),
    country: overrideCountry || 'Estados Unidos',
    countryFlag: overrideFlag || '🇺🇸',
  };
};
